pub(super) fn windows_key_name_to_keycode(name: &str) -> Option<u32> {
    match name.to_lowercase().as_str() {
        "f1" => Some(0x70),
        "f2" => Some(0x71),
        "f3" => Some(0x72),
        "f4" => Some(0x73),
        "f5" => Some(0x74),
        "f6" => Some(0x75),
        "f7" => Some(0x76),
        "f8" => Some(0x77),
        "f9" => Some(0x78),
        "f10" => Some(0x79),
        "f11" => Some(0x7A),
        "f12" => Some(0x7B),
        "up" => Some(0x26),
        "down" => Some(0x28),
        "left" => Some(0x25),
        "right" => Some(0x27),
        "space" => Some(0x20),
        "shift_l" | "shift_r" | "shift" => Some(0x10),
        "control_l" | "control_r" | "ctrl" | "control" => Some(0x11),
        "alt_l" | "alt_r" | "alt" | "menu" => Some(0x12),
        "super_l" | "super_r" | "win" | "meta" => Some(0x5B),
        "return" | "enter" => Some(0x0D),
        "escape" | "esc" => Some(0x1B),
        "tab" => Some(0x09),
        "backspace" | "back_space" => Some(0x08),
        "delete" => Some(0x2E),
        "insert" => Some(0x2D),
        "home" => Some(0x24),
        "end" => Some(0x23),
        "prior" | "pageup" | "page_up" => Some(0x21),
        "next" | "pagedown" | "page_down" => Some(0x22),
        "minus" => Some(0xBD),
        "equal" => Some(0xBB),
        "bracketleft" => Some(0xDB),
        "bracketright" => Some(0xDD),
        "semicolon" => Some(0xBA),
        "apostrophe" => Some(0xDE),
        "comma" => Some(0xBC),
        "period" => Some(0xBE),
        "slash" => Some(0xBF),
        "backslash" => Some(0xDC),
        "grave" => Some(0xC0),
        "print" | "printscreen" => Some(0x2C),
        "pause" => Some(0x13),
        "0" => Some(0x30),
        "1" => Some(0x31),
        "2" => Some(0x32),
        "3" => Some(0x33),
        "4" => Some(0x34),
        "5" => Some(0x35),
        "6" => Some(0x36),
        "7" => Some(0x37),
        "8" => Some(0x38),
        "9" => Some(0x39),
        "a" => Some(0x41),
        "b" => Some(0x42),
        "c" => Some(0x43),
        "d" => Some(0x44),
        "e" => Some(0x45),
        "f" => Some(0x46),
        "g" => Some(0x47),
        "h" => Some(0x48),
        "i" => Some(0x49),
        "j" => Some(0x4A),
        "k" => Some(0x4B),
        "l" => Some(0x4C),
        "m" => Some(0x4D),
        "n" => Some(0x4E),
        "o" => Some(0x4F),
        "p" => Some(0x50),
        "q" => Some(0x51),
        "r" => Some(0x52),
        "s" => Some(0x53),
        "t" => Some(0x54),
        "u" => Some(0x55),
        "v" => Some(0x56),
        "w" => Some(0x57),
        "x" => Some(0x58),
        "y" => Some(0x59),
        "z" => Some(0x5A),
        _ => None,
    }
}
